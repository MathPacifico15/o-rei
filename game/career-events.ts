export function selectCareerEvents(state: CareerState, player: Player, random:()=>number): CareerEvent[] {
  const blocked=new Set(state.history.slice(-3).flatMap(s=>s.events.map(e=>e.id)));
  const contextual: CareerEvent[] = [
    {id:'coletiva-momento',context:'imprensa',title:'O microfone está aberto',copy:player.form>=70?'A imprensa pergunta o segredo da boa fase.':'A imprensa questiona como você pretende recuperar a confiança.',choices:[{label:'Destacar o trabalho coletivo',idolatry:2,fame:1},{label:'Assumir a responsabilidade e prometer reação',fame:2,form:-1},{label:'Evitar promessas e falar da preparação',form:1}]},
    ...(player.age<=21?[{id:'base-conselho',context:'base',title:'Apressar os passos?',copy:'Um colega da base pergunta se deve procurar outro clube para jogar mais.',choices:[{label:'Sugerir uma conversa com o treinador',idolatry:1},{label:'Incentivar a busca por minutos',fame:1}]}]:[]),
    ...(state.contract.seasonsRemaining<=1?[{id:'contrato-ruido',context:'contrato',title:'O futuro virou assunto',copy:'Uma rádio especula sobre seu contrato. Nada foi assinado.',choices:[{label:'Reafirmar o compromisso com o presente',idolatry:2},{label:'Manter as opções abertas',fame:1,idolatry:-1}]}]:[]),
    {id:`posicao-${player.position}`,context:'posição',title:'Um detalhe do seu jogo',copy:player.position==='GOL'?'A comissão quer ouvir sua leitura das bolas aéreas.':player.position==='ATA'?'O treinador quer ajustar sua movimentação entre os zagueiros.':'O auxiliar quer discutir como você encontra espaço entre as linhas.',choices:[{label:'Trabalhar o ajuste com a comissão',form:2},{label:'Testar a ideia com os companheiros',idolatry:1,form:1}]},
    ...((player.clubIdolatry[player.clubId]??0)>=80?[{id:'torcida-homenagem',context:'torcida',title:'Seu nome na arquibancada',copy:'A torcida quer organizar uma pequena homenagem pela sua trajetória no clube.',choices:[{label:'Participar e agradecer ao grupo',idolatry:1,form:-1},{label:'Dedicar a homenagem aos colegas',fame:1}]}]:[]),
    ...(player.age>=32?[{id:'veterano-ritmo',context:'idade',title:'Escolher as batalhas',copy:'O preparador sugere ajustar o ritmo dos trabalhos extras nesta fase da carreira.',choices:[{label:'Concentrar a energia nos jogos',form:2},{label:'Usar o tempo para orientar a base',idolatry:2,form:-1}]}]:[]),
  ];
  const pool=[...contextual,...everydayEvents].filter(e=>!blocked.has(e.id));
  const count=2+Math.floor(random()*3), selected:CareerEvent[]=[];
  if(contextual[0]&&!blocked.has(contextual[0].id)) selected.push(contextual[0]);
  while(selected.length<count&&pool.length){const index=Math.floor(random()*pool.length);const [e]=pool.splice(index,1);if(!selected.some(x=>x.id===e.id))selected.push(e);}
  return selected;
}
