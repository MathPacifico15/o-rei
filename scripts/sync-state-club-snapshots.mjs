const endpoint = "https://pt.wikipedia.org/w/api.php";
const sleep = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));
function api(parameters) { return `${endpoint}?${new URLSearchParams({ format: "json", ...parameters })}`; }

async function participantSection(title) {
  const result = await (await fetch(api({ action: "parse", page: title, prop: "sections" }), { headers: { "user-agent": "O-REI-catalog-sync/1.0" } })).json();
  const sections = result.parse?.sections ?? [];
  const match = sections.find((section) => /equipes|participantes|clubes/i.test(section.line));
  if (!match) throw new Error(`${title}: seção de participantes não encontrada`);
  return match.index;
}

function extractFirstLinkFromRows(html) {
  const names = [];
  for (const row of html.match(/<tr[\s\S]*?<\/tr>/g) ?? []) {
    const cell = row.match(/<(?:td|th)[^>]*>[\s\S]*?<\/(?:td|th)>/i)?.[0];
    const link = cell?.match(/<a [^>]*>([\s\S]*?)<\/a>/i)?.[1];
    if (!link) continue;
    const name = link.replace(/<[^>]+>/g, "").replace(/&nbsp;/g, " ").trim();
    if (name && !/equipe|clube|cidade|títulos|participante/i.test(name)) names.push(name);
  }
  return [...new Set(names)];
}

async function fetchState([competitionId, query]) {
  const search = await (await fetch(api({ action: "query", list: "search", srsearch: query, srlimit: "5" }), { headers: { "user-agent": "O-REI-catalog-sync/1.0" } })).json();
  const title = search.query?.search?.find((item) => /2026/.test(item.title))?.title;
  if (!title) throw new Error(`${query}: página de edição 2026 não encontrada`);
  await sleep(350);
  const section = await participantSection(title);
  await sleep(350);
  const page = await (await fetch(api({ action: "parse", page: title, prop: "text", section }), { headers: { "user-agent": "O-REI-catalog-sync/1.0" } })).json();
  const clubs = extractFirstLinkFromRows(page.parse?.text?.["*"] ?? "");
  if (clubs.length < 4) throw new Error(`${title}: extração retornou apenas ${clubs.length} clubes`);
  return { competitionId, country: "Brasil", clubs, source: api({ action: "parse", page: title, prop: "text", section }) };
}

const snapshots = [];
for (const state of states) {
  snapshots.push(await fetchState(state));
  await sleep(500);
}
